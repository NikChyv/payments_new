-- pgTAP: адресные уведомления бухгалтерам.
--
-- Ради чего тест написан: в приложении бухгалтер видит только своих клиентов,
-- а в Telegram уведомления по всем клиентам уходили всем бухгалтерам разом.
-- Проверяем правило, по которому теперь выбирается адресат, — оно одно на
-- «новую заявку», «клиент ответил», «клиент изменил» и утреннее письмо:
--   • бухгалтеру — только по его клиентам;
--   • админу — по всем;
--   • клиент без бухгалтера — админу;
--   • бухгалтер без Telegram — админу, и функция узнаёт об этом, чтобы
--     записать отказ, а не промолчать.

begin;
select plan(17);

-- Чужие сотрудники в локальной базе (сид, стенд uicheck) не должны попадать в
-- адресаты этого теста. Внутри транзакции, откат вернёт как было.
update staff set telegram_id = null;

insert into auth.users (id) values
  ('0000a0a0-0000-0000-0000-00000000a0a0'),
  ('0000b1b1-0000-0000-0000-00000000b1b1'),
  ('0000c2c2-0000-0000-0000-00000000c2c2'),
  ('0000d3d3-0000-0000-0000-00000000d3d3');

-- Ольга — бухгалтер с Telegram, но без клиентов в этом тесте. Без неё проверка
-- «и больше никому» ничего бы не доказывала: если сломать правило и слать всем
-- сотрудникам, ответ по клиенту Валентины случайно совпал бы с правильным.
insert into staff (id, name, is_admin, telegram_id) values
  ('0000a0a0-0000-0000-0000-00000000a0a0', 'Админ',    true,  100),
  ('0000b1b1-0000-0000-0000-00000000b1b1', 'Валентина', false, 200),
  ('0000c2c2-0000-0000-0000-00000000c2c2', 'Татьяна',   false, null),
  ('0000d3d3-0000-0000-0000-00000000d3d3', 'Ольга',     false, 300);

insert into clients (id, name, token, staff_id) values
  ('a0000000-0000-0000-0000-00000000000a', 'Фирма Валентины', 'tokAddrV', '0000b1b1-0000-0000-0000-00000000b1b1'),
  ('a0000000-0000-0000-0000-00000000000b', 'Фирма Татьяны',   'tokAddrT', '0000c2c2-0000-0000-0000-00000000c2c2'),
  ('a0000000-0000-0000-0000-00000000000c', 'Фирма Админа',    'tokAddrA', '0000a0a0-0000-0000-0000-00000000a0a0'),
  ('a0000000-0000-0000-0000-00000000000d', 'Ничья фирма',     'tokAddrN', null);

-- ---- 1-2) доступ: номера сотрудников наружу не отдаются ----
select ok(not has_function_privilege('anon', 'public.notify_staff_chats(uuid)', 'EXECUTE'),
          'аноним не узнаёт chat_id сотрудников');
select ok(not has_function_privilege('authenticated', 'public.notify_staff_chats(uuid)', 'EXECUTE'),
          'вошедший сотрудник тоже — функцию зовут только уведомления');

-- ---- 3-4) клиент бухгалтера с Telegram ----
select is(notify_staff_chats('a0000000-0000-0000-0000-00000000000a') -> 'chats',
          '["100", "200"]'::jsonb,
          'по клиенту Валентины — ей и админу, и больше никому');
select is(notify_staff_chats('a0000000-0000-0000-0000-00000000000a') ->> 'unreachable',
          null::text,
          'бухгалтер на связи — жаловаться не на что');

-- ---- 5-6) клиент бухгалтера без Telegram ----
select is(notify_staff_chats('a0000000-0000-0000-0000-00000000000b') -> 'chats',
          '["100"]'::jsonb,
          'Татьяна без Telegram — уведомление всё равно уходит админу, а не в пустоту');
select is(notify_staff_chats('a0000000-0000-0000-0000-00000000000b') ->> 'unreachable',
          'Татьяна',
          'и функция знает, кто недоступен, — чтобы записать отказ');

-- ---- 7) бухгалтер клиента сам админ ----
select is(notify_staff_chats('a0000000-0000-0000-0000-00000000000c') -> 'chats',
          '["100"]'::jsonb,
          'админ ведёт клиента сам — получает один раз, а не дважды');

-- ---- 8-10) клиента нет или он ничей ----
select is(notify_staff_chats('a0000000-0000-0000-0000-00000000000d') -> 'chats',
          '["100"]'::jsonb,
          'клиент без бухгалтера — админу');
select is(notify_staff_chats(null) -> 'chats',
          '["100"]'::jsonb,
          'заявка без клиента — админу');
select is(notify_staff_chats('ffffffff-ffff-ffff-ffff-ffffffffffff') -> 'chats',
          '["100"]'::jsonb,
          'несуществующий клиент — не падаем, шлём админу');

-- ---- 11-15) утреннее письмо ----
insert into payments (id, client, client_id, payee, amount, requisites, due, recurrence,
                      purpose, status, need_receipt, created_at) values
  ('addrV', 'Фирма Валентины', 'a0000000-0000-0000-0000-00000000000a', 'Платёж Валентины',
   100, '', (now() at time zone 'Europe/Minsk')::date, 'once', '', 'new', false, now()),
  ('addrT', 'Фирма Татьяны',   'a0000000-0000-0000-0000-00000000000b', 'Платёж Татьяны',
   200, '', (now() at time zone 'Europe/Minsk')::date, 'once', '', 'new', false, now()),
  ('addrN', 'Ничья фирма',     'a0000000-0000-0000-0000-00000000000d', 'Ничей платёж',
   300, '', (now() at time zone 'Europe/Minsk')::date, 'once', '', 'new', false, now());

select ok(daily_reminder_message('0000b1b1-0000-0000-0000-00000000b1b1') like '%Платёж Валентины%',
          'в письме Валентины — её клиент');
select ok(daily_reminder_message('0000b1b1-0000-0000-0000-00000000b1b1') not like '%Платёж Татьяны%',
          'клиента Татьяны в письме Валентины нет — ради этого всё и делалось');
select ok(daily_reminder_message('0000b1b1-0000-0000-0000-00000000b1b1') not like '%Ничей платёж%',
          'ничьего клиента в письме бухгалтера тоже нет');

select ok(daily_reminder_message('0000a0a0-0000-0000-0000-00000000a0a0') like '%Платёж Валентины%'
      and daily_reminder_message('0000a0a0-0000-0000-0000-00000000a0a0') like '%Платёж Татьяны%'
      and daily_reminder_message('0000a0a0-0000-0000-0000-00000000a0a0') like '%Ничей платёж%',
          'в письме админа — все клиенты, включая ничьих');

select ok(daily_reminder_message() like '%Платёж Татьяны%',
          'запасное письмо без адресата по-прежнему содержит всех');

-- ---- 16-17) админа без Telegram нет — бухгалтер всё равно получает своё ----
update staff set telegram_id = null where id = '0000a0a0-0000-0000-0000-00000000a0a0';

select is(notify_staff_chats('a0000000-0000-0000-0000-00000000000a') -> 'chats',
          '["200"]'::jsonb,
          'без админа на связи бухгалтер получает уведомления по своему клиенту');
select is(notify_staff_chats('a0000000-0000-0000-0000-00000000000d') -> 'chats',
          '[]'::jsonb,
          'а ничьего клиента слать некому — пусто, и функция это увидит');

select * from finish();
rollback;
