-- pgTAP: рабочий график пн–пт до 17:00 (Europe/Minsk).
-- Ключевые сценарии проверяются с ЗАДАННЫМ моментом времени, поэтому
-- результат не зависит от того, когда прогоняются тесты.
--
-- Опорные даты: 2026-07-24 пт, 25 сб, 26 вс, 27 пн, 28 вт.

begin;
select plan(19);

-- ---------- next_working_day ----------
select is( next_working_day(date '2026-07-24'), date '2026-07-27', 'после пятницы — понедельник' );
select is( next_working_day(date '2026-07-25'), date '2026-07-27', 'после субботы — понедельник' );
select is( next_working_day(date '2026-07-26'), date '2026-07-27', 'после воскресенья — понедельник' );
select is( next_working_day(date '2026-07-27'), date '2026-07-28', 'после понедельника — вторник' );

-- ---------- ГЛАВНЫЙ СЦЕНАРИЙ: заявка «на сегодня», когда работать уже нельзя ----------
-- воскресенье днём, срок «сегодня» -> понедельник (пример из ТЗ)
select is(
  adjust_due_date(date '2026-07-26', timestamp '2026-07-26 13:00'),
  date '2026-07-27',
  'воскресенье, срок «сегодня» -> переносится на понедельник'
);

-- суббота -> понедельник
select is(
  adjust_due_date(date '2026-07-25', timestamp '2026-07-25 10:00'),
  date '2026-07-27',
  'суббота, срок «сегодня» -> понедельник'
);

-- пятница после 17:00 -> понедельник (через выходные)
select is(
  adjust_due_date(date '2026-07-24', timestamp '2026-07-24 18:30'),
  date '2026-07-27',
  'пятница вечером -> понедельник'
);

-- будний день после 17:00 -> следующий день
select is(
  adjust_due_date(date '2026-07-27', timestamp '2026-07-27 17:30'),
  date '2026-07-28',
  'понедельник вечером -> вторник'
);

-- ---------- в рабочее время ничего не двигаем ----------
select is(
  adjust_due_date(date '2026-07-27', timestamp '2026-07-27 10:00'),
  date '2026-07-27',
  'рабочее время, срок «сегодня» -> остаётся сегодня'
);

-- граница 17:00 включительно — уже поздно
select is(
  adjust_due_date(date '2026-07-27', timestamp '2026-07-27 17:00'),
  date '2026-07-28',
  'ровно 17:00 — рабочий день закончен, перенос'
);

-- за минуту до конца — успеваем
select is(
  adjust_due_date(date '2026-07-27', timestamp '2026-07-27 16:59'),
  date '2026-07-27',
  '16:59 — ещё успеваем, дата не меняется'
);

-- ---------- будущее ----------
select throws_ok(
  $$ select adjust_due_date(date '2026-08-01', timestamp '2026-07-27 10:00') $$,
  'P0001',
  'В выходной платёж не проводится. Выберите рабочий день (пн–пт).',
  'будущая суббота — ошибка'
);

select throws_ok(
  $$ select adjust_due_date(date '2026-08-02', timestamp '2026-07-27 10:00') $$,
  'P0001',
  'В выходной платёж не проводится. Выберите рабочий день (пн–пт).',
  'будущее воскресенье — ошибка'
);

select is(
  adjust_due_date(date '2026-07-31', timestamp '2026-07-27 10:00'),
  date '2026-07-31',
  'будущая пятница проходит без изменений'
);

-- завтра-выходной тоже отсекается (клиент в пятницу просит «на субботу»)
select throws_ok(
  $$ select adjust_due_date(date '2026-07-25', timestamp '2026-07-24 12:00') $$,
  'P0001',
  'В выходной платёж не проводится. Выберите рабочий день (пн–пт).',
  'в пятницу срок «на завтра, субботу» — ошибка'
);

-- ---------- прошлое не трогаем ----------
select is(
  adjust_due_date(date '2026-07-20', timestamp '2026-07-27 10:00'),
  date '2026-07-20',
  'прошлый будний день не меняется'
);

select is(
  adjust_due_date(date '2026-07-25', timestamp '2026-07-27 10:00'),
  date '2026-07-25',
  'прошлая суббота не меняется (просрочка — сигнал бухгалтеру)'
);

-- ---------- боевая версия (без явного времени) согласована с тестируемой ----------
select is(
  adjust_due_date(current_date - 5),
  adjust_due_date(current_date - 5, (now() at time zone 'Europe/Minsk')::timestamp),
  'версия с одним аргументом делегирует в версию с временем'
);

select is( adjust_due_date(null::date), null, 'null-дата возвращается как есть' );

select * from finish();
rollback;
