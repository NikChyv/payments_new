-- pgTAP: подпись «чьё это» при общем Telegram (13.10).
--
-- Ради чего тест написан: у двух бухгалтеров один телефон и один Telegram, а
-- учётки и клиенты разные. В общий чат приходит всё по клиентам обоих — и
-- утренние письма (по одному на учётку), и «новая заявка», «клиент ответил»,
-- «клиент изменил». Без имени не понять, чьё какое. Проверяем, что имя
-- появляется ровно в этом случае — и что у всех остальных всё осталось прежним.
--
-- Утреннее письмо собирает база целиком, поэтому здесь сверяется сам текст.
-- У мгновенных уведомлений база только называет, кому и чьё (поле `shared`),
-- а текст собирают функции — их проверяет tools/notifycheck.mjs.
begin;
select plan(14);

insert into auth.users (id) values
  ('00000f01-0000-0000-0000-000000000f01'),
  ('00000f02-0000-0000-0000-000000000f02'),
  ('00000f03-0000-0000-0000-000000000f03'),
  ('00000f04-0000-0000-0000-000000000f04'),
  ('00000f05-0000-0000-0000-000000000f05');

-- Валентина и Елена делят один Telegram; у Татьяны свой; у двоих последних
-- Telegram не внесён вовсе — «нет номера» не должно считаться совпадением.
insert into staff (id, name, is_admin, telegram_id) values
  ('00000f01-0000-0000-0000-000000000f01', 'Валентина',  false, 880001),
  ('00000f02-0000-0000-0000-000000000f02', 'Елена <Е>',  false, 880001),
  ('00000f03-0000-0000-0000-000000000f03', 'Татьяна',    false, 880002),
  ('00000f04-0000-0000-0000-000000000f04', 'Без номера', false, null),
  ('00000f05-0000-0000-0000-000000000f05', 'Тоже без',   false, null);

insert into clients (id, name, token, staff_id) values
  ('f0000000-0000-0000-0000-00000000000a', 'Фирма Валентины', 'tokShV', '00000f01-0000-0000-0000-000000000f01'),
  ('f0000000-0000-0000-0000-00000000000b', 'Фирма Елены',     'tokShE', '00000f02-0000-0000-0000-000000000f02'),
  ('f0000000-0000-0000-0000-00000000000c', 'Фирма Татьяны',   'tokShT', '00000f03-0000-0000-0000-000000000f03'),
  ('f0000000-0000-0000-0000-00000000000d', 'Ничья фирма',     'tokShN', null);

delete from payments;
insert into payments (id, client, client_id, payee, amount, due, recurrence, status, created_at) values
  ('sh-val', 'Фирма Валентины', 'f0000000-0000-0000-0000-00000000000a', 'Платёж Валентины',
   100, (now() at time zone 'Europe/Minsk')::date, 'once', 'new', now());

-- ---- 1-4) общий Telegram: письма различимы ----
select matches(daily_reminder_message('00000f01-0000-0000-0000-000000000f01'),
               '^📅 <b>Платежи на \d\d\.\d\d\.\d{4} · Валентина</b>\n',
               'общий Telegram — в заголовке письма имя бухгалтера');
select matches(daily_reminder_message('00000f02-0000-0000-0000-000000000f02'),
               '^📅 <b>Платежи на \d\d\.\d\d\.\d{4} · Елена &lt;Е&gt;</b>\n',
               'у второго в том же чате — своё имя, и оно экранировано');
select ok(daily_reminder_message('00000f01-0000-0000-0000-000000000f01') like '%Платёж Валентины%',
          'список в подписанном письме на месте');
select ok(daily_reminder_message('00000f02-0000-0000-0000-000000000f02') like '%Нет платежей на сегодня%'
          and daily_reminder_message('00000f02-0000-0000-0000-000000000f02') not like '%Платёж Валентины%',
          'пустое письмо второго подписано им — видно, у кого из двоих пусто; чужого в нём нет');

-- ---- 5-7) у остальных письмо прежнее ----
select matches(daily_reminder_message('00000f03-0000-0000-0000-000000000f03'),
               '^📅 <b>Платежи на \d\d\.\d\d\.\d{4}</b>\n',
               'свой отдельный Telegram — заголовок без имени, как раньше');
select matches(daily_reminder_message('00000f04-0000-0000-0000-000000000f04'),
               '^📅 <b>Платежи на \d\d\.\d\d\.\d{4}</b>\n',
               'Telegram не внесён у двоих — это не «общий», имени нет');
select matches(daily_reminder_message(),
               '^📅 <b>Платежи на \d\d\.\d\d\.\d{4}</b>\n',
               'запасное письмо без адресата — без имени');

-- ---- 8-12) мгновенные уведомления: база говорит функции, чьё сообщение ----
select is(notify_staff_chats('f0000000-0000-0000-0000-00000000000a') -> 'shared',
          '{"chat": "880001", "name": "Валентина"}'::jsonb,
          'клиент Валентины: чат общий — база называет чат и её имя');
select is(notify_staff_chats('f0000000-0000-0000-0000-00000000000b') -> 'shared',
          '{"chat": "880001", "name": "Елена <Е>"}'::jsonb,
          'клиент Елены: тот же чат, имя другое (экранирует его уже функция)');
select ok(notify_staff_chats('f0000000-0000-0000-0000-00000000000a') -> 'chats' @> '["880001"]'::jsonb
          and not (notify_staff_chats('f0000000-0000-0000-0000-00000000000a') -> 'chats' @> '["880002"]'::jsonb),
          'адресаты прежние: общий чат в списке, чужой бухгалтер — нет');
select is(jsonb_typeof(notify_staff_chats('f0000000-0000-0000-0000-00000000000c') -> 'shared'), 'null',
          'клиент Татьяны: Telegram у неё свой — подписывать нечего');
select is(jsonb_typeof(notify_staff_chats('f0000000-0000-0000-0000-00000000000d') -> 'shared'), 'null',
          'ничья фирма: бухгалтера нет — подписи нет');

-- ---- 13-14) общий Telegram перестал быть общим ----
update staff set telegram_id = 880003 where id = '00000f02-0000-0000-0000-000000000f02';
select matches(daily_reminder_message('00000f01-0000-0000-0000-000000000f01'),
               '^📅 <b>Платежи на \d\d\.\d\d\.\d{4}</b>\n',
               'второй завёл свой Telegram — имя из заголовка первого пропало само');

select is(jsonb_typeof(notify_staff_chats('f0000000-0000-0000-0000-00000000000a') -> 'shared'), 'null',
          'и из мгновенных уведомлений по клиентам первого — тоже');

select * from finish();
rollback;
