-- Аноним не получает прямых прав на таблицы — явно, а не по случайности
--
-- Найдено 16.09.2026: CI красный с 27.08, и все четыре упавших теста — про
-- права anon на payments. На проде прав у анонима нет (REST отвечает
-- «permission denied for table payments»), локальный стек разработчика тоже
-- чистый. Разница в том, как создаётся база:
--
--   свежий образ Supabase раздаёт default privileges роли postgres в схеме
--   public так, что КАЖДАЯ новая таблица сразу получает ALL для anon и
--   authenticated. Миграции создают таблицы от postgres — значит на базе,
--   поднятой из миграций с нуля (CI, новый стенд, восстановление по RUNBOOK),
--   аноним получал полный доступ к payments. От данных его отделяла бы только
--   RLS.
--
-- Та же ловушка, что CLAUDE.md, грабли №3, только для таблиц: «нет grant» не
-- значит «нет права». Закрываем двумя шагами:
--   1) снимаем всё с anon на таблицах, где это было неявным;
--   2) меняем default privileges, чтобы следующая таблица не открылась так же.
--
-- M6.5 (GRANT ALL анониму на clients, staff, tg_sessions) закрывается здесь
-- же: клиент ходит только через RPC по токену (SECURITY DEFINER), бот — под
-- service_role, прямого чтения таблиц анонимом нет нигде.
--
-- На проде шаг 1 для payments ничего не меняет, для остальных трёх снимает
-- гигиенический мусор. authenticated не трогаем: сотрудники работают с
-- таблицами напрямую, доступ им режут политики RLS.
-- ---------------------------------------------------------------------------

revoke all on table public.payments    from anon;
revoke all on table public.clients     from anon;
revoke all on table public.staff       from anon;
revoke all on table public.tg_sessions from anon;

-- Следующие таблицы, созданные миграциями (они идут от postgres), анониму по
-- умолчанию ничего не дают. Нужен доступ — выдавать явно. Функций это не
-- касается: клиентские RPC живут на EXECUTE для anon, и правило для них в
-- CLAUDE.md остаётся прежним — служебные закрывать явным revoke.
alter default privileges for role postgres in schema public
  revoke all on tables from anon;
