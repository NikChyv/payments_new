-- Платёжный документ файлом, а не в чате.
--
-- Клиент при заявке ставит галочку «нужен платёжный документ» (need_receipt).
-- Дальше бухгалтер жал «Документ отправлен», заявка уходила в статус sent — но
-- сам файл летел в личный чат. Софт знал, что документ обещан, и не знал, что
-- он есть; клиенту потом нечего было переслать поставщику.
--
-- Файлы бухгалтера держим ОТДЕЛЬНО от payments.files. Причина конкретная:
-- file_url/file_name — зеркало ПЕРВОГО элемента files, их читают утренняя
-- рассылка, notify-payment и Telegram-бот. Подмешаешь платёжку в files —
-- и она всплывёт в уведомлении о новой заявке как «счёт от клиента».
-- Плюс в кабинете «мой счёт» и «документ от бухгалтера» должны читаться
-- как разные вещи.
--
-- Клиентские RPC менять не нужно: list_payments_by_token возвращает
-- SETOF payments, поэтому новая колонка приезжает клиенту сама — без
-- перегрузок функций и без повторной выдачи прав (см. CLAUDE.md).

alter table public.payments
  add column if not exists staff_files jsonb not null default '[]'::jsonb;

-- Сколько документов уже ушло клиенту в Telegram. Именно счётчик, а не флаг:
-- документов может быть несколько (платёжка + акт), они могут прикладываться
-- не разом, и после первой отправки остальные обязаны дойти. Функция шлёт
-- элементы, начиная с этого номера, и увеличивает его только после успешной
-- отправки — как это уже сделано с client_paid_notified.
alter table public.payments
  add column if not exists client_docs_notified int not null default 0;

